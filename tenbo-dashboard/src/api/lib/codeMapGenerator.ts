/**
 * codeMapGenerator.ts — deterministic structural code-map sections generated
 * from the source index (td-026).
 *
 * A layer's `code-map.md` mixes hand-written prose (intent, gotchas, "read
 * this first") with structural facts the source index already knows (entry
 * points, exports, dependency edges, file inventory). This module generates
 * ONLY the structural facts, inside an explicit marker pair
 * (`CODE_MAP_MARKER_BEGIN` / `CODE_MAP_MARKER_END`), and never touches a
 * single byte outside that region. See `upsertMarkedRegion` for the
 * byte-preservation contract.
 */
import { createHash } from 'node:crypto';
import { readState, readLayerDocFile, writeLayerDocFile } from './tenboFs';
import { buildSourceIndex } from './sourceIndex/build';
import { checkSourceIndexFreshness, readSourceIndex, writeSourceIndex } from './sourceIndex/store';
import type { Layer, Scope, TenboState } from '../../types';
import type { SourceIndex, SourceIndexFile } from './sourceIndex/types';

export const CODE_MAP_MARKER_BEGIN = '<!-- tenbo:auto:code-map begin -->';
export const CODE_MAP_MARKER_END = '<!-- tenbo:auto:code-map end -->';

const ENTRY_POINT_CAP = 8;
const FILES_CAP = 150;
const EXPORTS_PER_FILE_CAP = 6;
const EDGES_CAP = 60;

export type CodeMapGeneratorErrorCode =
  | 'missing_source_index'
  | 'corrupt_source_index'
  | 'incompatible_source_index'
  | 'not_found'
  | 'ambiguous_markers';

export class CodeMapGeneratorError extends Error {
  code: CodeMapGeneratorErrorCode;
  constructor(code: CodeMapGeneratorErrorCode, message: string) {
    super(message);
    this.name = 'CodeMapGeneratorError';
    this.code = code;
  }
}

export function isCodeMapGeneratorError(err: unknown): err is CodeMapGeneratorError {
  return err instanceof CodeMapGeneratorError;
}

// ---------------------------------------------------------------------------
// Structural block generation
// ---------------------------------------------------------------------------

/**
 * Per-layer content hash — derived ONLY from the paths (and per-file content
 * hashes, from `index.inputs`) of the files that belong to *this* layer.
 *
 * Previously this hashed the entire index and embedded the same hash into
 * every layer's `code-map.md`, so editing one file in layer A marked ALL
 * layers stale and rewrote all of their `code-map.md` files — content-free
 * churn, and false `--check` staleness in CI for layers nothing changed in.
 * Scoping the hash to the layer's own files fixes that: editing a file in
 * layer A no longer changes layer B's embedded hash (or block text), so only
 * layer A is reported/rewritten.
 *
 * A layer's own `code-map.md` is never itself one of "this layer's files"
 * (`layerFilesData` resolves files from `scope.path` glob patterns, and
 * `code-map.md` always lives under `.tenbo/scopes/**`, outside any
 * `scope.path`), so there is no self-referential loop to guard against here.
 */
export function layerContentHash(index: SourceIndex, scope: Scope, layer: Layer): string {
  const { files } = layerFilesData(index, scope.id, layer.id);
  const canonical = files
    .map((file) => `${file.path}=${index.inputs[file.path] ?? ''}`)
    .join('\n');
  return createHash('sha256').update(canonical).digest('hex').slice(0, 12);
}

/**
 * Matches the auto-generated marker comment's embedded content hash — the
 * first line inside the marker region emitted by `buildStructuralBlock`
 * (`<!-- Auto-generated by \`tenbo-dashboard code-map generate\` from the
 * source index (content HASH). ... -->`). Deliberately just a text match
 * (not a full marker-region parse via `findMarkerLines`) — this is a
 * read-only staleness *signal*, not a write path, so it doesn't need the
 * ambiguous-marker guard `upsertMarkedRegion` uses before mutating a file.
 */
const EMBEDDED_CODE_MAP_HASH_RE = /Auto-generated by `tenbo-dashboard code-map generate` from the source index \(content ([0-9a-f]+)\)/;

export interface LayerCodeMapStaleness {
  stale: boolean;
  /** Present only when `stale` is true. */
  reason?: string;
  embedded_hash?: string;
  current_hash?: string;
}

/**
 * Cheap doc-staleness signal for one layer (td-027): compares the content
 * hash already embedded in `code-map.md`'s generated marker region (from the
 * last `code-map generate` run) against the layer's *current*
 * `layerContentHash` — no need to rebuild the full structural block just to
 * check staleness. Fail-open: a missing `code-map.md`, or one with no
 * generated marker region yet, is reported as not stale (nothing to compare
 * against) rather than thrown.
 */
export function isLayerCodeMapStale(
  repoRoot: string,
  index: SourceIndex,
  scope: Scope,
  layer: Layer,
): LayerCodeMapStaleness {
  let existing: string | null;
  try {
    existing = readLayerDocFile(repoRoot, scope.id, layer.id, 'code-map.md');
  } catch {
    return { stale: false };
  }
  if (!existing) return { stale: false };
  const match = existing.match(EMBEDDED_CODE_MAP_HASH_RE);
  if (!match) return { stale: false };
  const embeddedHash = match[1];
  const currentHash = layerContentHash(index, scope, layer);
  if (embeddedHash === currentHash) return { stale: false };
  return {
    stale: true,
    reason: `generated code-map region (hash ${embeddedHash}) is stale vs. the current source index (hash ${currentHash})`,
    embedded_hash: embeddedHash,
    current_hash: currentHash,
  };
}

function truncatedList<T>(items: T[], cap: number): { shown: T[]; more: number } {
  if (items.length <= cap) return { shown: items, more: 0 };
  return { shown: items.slice(0, cap), more: items.length - cap };
}

interface LayerFilesData {
  files: SourceIndexFile[];
  publicEntrypoints: string[];
}

function layerFilesData(index: SourceIndex, scopeId: string, layerId: string): LayerFilesData {
  const files = index.files
    .filter((file) => file.scope === scopeId && file.layers.includes(layerId))
    .slice()
    .sort((a, b) => a.path.localeCompare(b.path));
  const entry = index.layers.find((layer) => layer.scope === scopeId && layer.layer === layerId);
  return { files, publicEntrypoints: entry?.public_entrypoints ?? [] };
}

interface ScoredEntryPoint {
  path: string;
  fanIn: number;
  explicit: boolean;
}

/**
 * Entry-point heuristic: files explicitly named as the layer's public
 * entrypoints (`index.ts`/`index.tsx`, per the source index builder), plus
 * files with the highest fan-in from other files *within this layer*.
 * Deterministic tie-break: explicit first, then fan-in desc, then path asc.
 */
function computeEntryPoints(files: SourceIndexFile[], publicEntrypoints: string[]): ScoredEntryPoint[] {
  const layerPaths = new Set(files.map((file) => file.path));
  const explicitSet = new Set(publicEntrypoints);
  const scored: ScoredEntryPoint[] = files.map((file) => ({
    path: file.path,
    fanIn: file.imported_by.filter((importer) => layerPaths.has(importer)).length,
    explicit: explicitSet.has(file.path),
  }));
  scored.sort((a, b) => {
    if (a.explicit !== b.explicit) return a.explicit ? -1 : 1;
    if (b.fanIn !== a.fanIn) return b.fanIn - a.fanIn;
    return a.path.localeCompare(b.path);
  });
  return scored.filter((entry) => entry.explicit || entry.fanIn > 0).slice(0, ENTRY_POINT_CAP);
}

/** Maps every file in `scopeId` to its primary (first) owning layer id, per the index. */
function primaryLayerByFile(index: SourceIndex, scopeId: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const file of index.files) {
    if (file.scope !== scopeId) continue;
    if (file.layers[0]) map.set(file.path, file.layers[0]);
  }
  return map;
}

interface Edge {
  from: string;
  to: string;
}

interface CrossEdge extends Edge {
  toLayer: string;
}

interface DependencyEdges {
  intra: Edge[];
  cross: CrossEdge[];
}

/** Dependency edges (from `imports`) split into intra-layer and cross-layer, deduped and sorted. */
function computeEdges(files: SourceIndexFile[], layerId: string, layerOfFile: Map<string, string>): DependencyEdges {
  const intraByKey = new Map<string, Edge>();
  const crossByKey = new Map<string, CrossEdge>();
  for (const file of files) {
    for (const target of file.imports) {
      if (target === file.path) continue;
      const targetLayer = layerOfFile.get(target);
      if (targetLayer === undefined) continue; // target outside the indexed scope
      if (targetLayer === layerId) {
        intraByKey.set(`${file.path}|${target}`, { from: file.path, to: target });
      } else {
        crossByKey.set(`${file.path}|${targetLayer}|${target}`, { from: file.path, to: target, toLayer: targetLayer });
      }
    }
  }
  const intra = Array.from(intraByKey.values()).sort((a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to));
  const cross = Array.from(crossByKey.values()).sort((a, b) =>
    a.from.localeCompare(b.from) || a.toLayer.localeCompare(b.toLayer) || a.to.localeCompare(b.to));
  return { intra, cross };
}

export interface StructuralBlock {
  /** Markdown body between (not including) the marker comment lines. */
  body: string;
  /** Content hash of the source index snapshot this block was generated from. */
  hash: string;
}

/** Builds the deterministic structural markdown for one layer from the source index. */
export function buildStructuralBlock(index: SourceIndex, scope: Scope, layer: Layer): StructuralBlock {
  const { files, publicEntrypoints } = layerFilesData(index, scope.id, layer.id);
  const entryPoints = computeEntryPoints(files, publicEntrypoints);
  const layerOfFile = primaryLayerByFile(index, scope.id);
  const edges = computeEdges(files, layer.id, layerOfFile);
  const hash = layerContentHash(index, scope, layer);

  const lines: string[] = [];
  lines.push(
    `<!-- Auto-generated by \`tenbo-dashboard code-map generate\` from the source index (content ${hash}). `
    + 'Edits inside this block are overwritten on the next run — edit outside the markers instead. -->',
  );
  lines.push('');
  lines.push('### Entry points (auto)');
  if (entryPoints.length === 0) {
    lines.push('_None detected (no internal fan-in and no `index.ts`/`index.tsx` in this layer)._');
  } else {
    for (const entry of entryPoints) {
      const reason = entry.explicit ? 'public entrypoint' : `imported by ${entry.fanIn} file(s) in this layer`;
      lines.push(`- \`${entry.path}\` — ${reason}`);
    }
  }
  lines.push('');
  lines.push('### Files (auto)');
  if (files.length === 0) {
    lines.push('_No files indexed for this layer. Run `tenbo-dashboard index` if this looks wrong._');
  } else {
    lines.push('| File | Kind | Lines | Key exports |');
    lines.push('|---|---|---|---|');
    const { shown, more } = truncatedList(files, FILES_CAP);
    for (const file of shown) {
      const exportsResult = truncatedList(file.exports, EXPORTS_PER_FILE_CAP);
      const exportsCell = file.exports.length === 0
        ? '—'
        : exportsResult.shown.map((name) => `\`${name}\``).join(', ') + (exportsResult.more > 0 ? `, +${exportsResult.more} more` : '');
      lines.push(`| \`${file.path}\` | ${file.kind} | ${file.line_count} | ${exportsCell} |`);
    }
    if (more > 0) lines.push(`_+${more} more file(s) not shown (${files.length} total)._`);
  }
  lines.push('');
  lines.push('### Dependency edges (auto)');
  lines.push('**Intra-layer:**');
  if (edges.intra.length === 0) {
    lines.push('_None detected._');
  } else {
    const { shown, more } = truncatedList(edges.intra, EDGES_CAP);
    for (const edge of shown) lines.push(`- \`${edge.from}\` → \`${edge.to}\``);
    if (more > 0) lines.push(`_+${more} more edge(s) not shown._`);
  }
  lines.push('');
  lines.push('**Cross-layer:**');
  if (edges.cross.length === 0) {
    lines.push('_None detected._');
  } else {
    const { shown, more } = truncatedList(edges.cross, EDGES_CAP);
    for (const edge of shown) lines.push(`- \`${edge.from}\` → ${edge.toLayer}:\`${edge.to}\``);
    if (more > 0) lines.push(`_+${more} more edge(s) not shown._`);
  }

  return { body: lines.join('\n'), hash };
}

// ---------------------------------------------------------------------------
// Marker region upsert — the byte-preservation contract.
// ---------------------------------------------------------------------------

export interface MarkedRegionResult {
  content: string;
  /** True iff `content` differs from the input `existingContent`. */
  changed: boolean;
  /** True iff the input already contained a marker pair. */
  hadMarker: boolean;
}

/**
 * Splits `text` into lines, each retaining its own trailing line terminator
 * (`\n` or `\r\n`). Slicing/joining a contiguous subrange of the result with
 * `''` reconstructs the corresponding original bytes exactly — no terminator
 * has to be inferred or re-added.
 */
function splitLinesKeepEnds(text: string): string[] {
  const out: string[] = [];
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '\n') {
      out.push(text.slice(start, i + 1));
      start = i + 1;
    }
  }
  out.push(text.slice(start));
  return out;
}

/**
 * A marker only counts when it is *line-anchored*: the whole trimmed line
 * equals the marker text, not merely a substring somewhere on the line. This
 * is what makes region detection safe — a marker mentioned inside prose, or
 * inside a fenced code example that documents the marker syntax, does not
 * count as a real marker and cannot be mistaken for one.
 */
function findMarkerLines(lines: string[]): { begin: number[]; end: number[] } {
  const begin: number[] = [];
  const end: number[] = [];
  lines.forEach((line, idx) => {
    const trimmed = line.trim();
    if (trimmed === CODE_MAP_MARKER_BEGIN) begin.push(idx);
    if (trimmed === CODE_MAP_MARKER_END) end.push(idx);
  });
  return { begin, end };
}

/**
 * Replaces (or inserts) the marked structural region in `existingContent`,
 * leaving every other byte untouched.
 *
 * Marker detection is line-anchored and exhaustively counted first:
 *  - Zero begin and zero end markers → insert after the title line.
 *  - Exactly one begin, exactly one end, begin before end → replace that
 *    region; everything before and after is passed through via `.slice()`,
 *    preserved byte-for-byte.
 *  - Anything else (more than one begin, more than one end, end-before-begin,
 *    or a lone begin/end with no matching partner) is ambiguous. This
 *    generator never guesses in that case — it throws `CodeMapGeneratorError`
 *    and writes nothing, because guessing (e.g. "first occurrence wins") is
 *    exactly what silently corrupts hand-written prose: a code-map.md that
 *    documents the marker syntax inside a fenced example above the real
 *    generated block, or a file with two well-formed marker pairs, would
 *    otherwise have the wrong region overwritten while the real region goes
 *    stale forever.
 */
export function upsertMarkedRegion(existingContent: string, body: string, fallbackTitle: string): MarkedRegionResult {
  const eol = existingContent.includes('\r\n') ? '\r\n' : '\n';
  const regionBody = eol === '\n' ? body : body.replace(/\n/g, eol);
  const region = `${CODE_MAP_MARKER_BEGIN}${eol}${regionBody}${eol}${CODE_MAP_MARKER_END}`;

  const lines = splitLinesKeepEnds(existingContent);
  const { begin, end } = findMarkerLines(lines);

  if (begin.length > 0 || end.length > 0) {
    const wellFormedSinglePair = begin.length === 1 && end.length === 1 && end[0] > begin[0];
    if (!wellFormedSinglePair) {
      throw new CodeMapGeneratorError(
        'ambiguous_markers',
        'code-map.md has ambiguous or duplicate `tenbo:auto:code-map` markers '
        + `(found ${begin.length} begin marker line(s) and ${end.length} end marker line(s), not a single `
        + 'well-formed begin/end pair). Refusing to write — guessing which region is "real" risks silently '
        + 'corrupting hand-written prose (for example, a fenced example that shows the marker syntax, or a stray '
        + 'duplicate pair). Resolve by hand so the file has exactly one begin marker and one end marker, each alone '
        + 'on its own line, begin before end — then retry `code-map generate`.',
      );
    }

    const lineOffsets: number[] = [];
    let offset = 0;
    for (const line of lines) {
      lineOffsets.push(offset);
      offset += line.length;
    }
    const beginLineIdx = begin[0];
    const endLineIdx = end[0];
    const beginOffset = lineOffsets[beginLineIdx] + lines[beginLineIdx].indexOf(CODE_MAP_MARKER_BEGIN);
    const endOffset = lineOffsets[endLineIdx] + lines[endLineIdx].indexOf(CODE_MAP_MARKER_END) + CODE_MAP_MARKER_END.length;

    const before = existingContent.slice(0, beginOffset);
    const after = existingContent.slice(endOffset);
    const content = `${before}${region}${after}`;
    return { content, changed: content !== existingContent, hadMarker: true };
  }

  if (existingContent.length === 0) {
    const content = `# ${fallbackTitle} — Code Map${eol}${eol}${region}${eol}`;
    return { content, changed: true, hadMarker: false };
  }

  const splitLines = existingContent.split(/\r\n|\n/);
  const titleIdx = splitLines.findIndex((line) => /^#\s+/.test(line));
  const insertAt = titleIdx === -1 ? 0 : titleIdx + 1;
  const before = splitLines.slice(0, insertAt).join(eol);
  const after = splitLines.slice(insertAt).join(eol);
  const beforeSep = before.length > 0 ? `${eol}${eol}` : '';
  const afterSep = after.trim().length > 0 ? `${eol}${eol}` : eol;
  const content = `${before}${beforeSep}${region}${afterSep}${after}`;
  return { content, changed: true, hadMarker: false };
}

// ---------------------------------------------------------------------------
// Index loading — reuses the same freshness contract as `context`/`impact`,
// but (unlike those read-only consumers) rebuilds automatically when stale
// since regenerating code-maps from stale structural data would just bake
// the staleness into the docs. A missing/corrupt/incompatible index is not
// auto-built — fail with a clear pointer to `tenbo-dashboard index` instead.
// ---------------------------------------------------------------------------

function loadIndexForGeneration(repoRoot: string): SourceIndex {
  const existing = readSourceIndex(repoRoot);
  const freshness = checkSourceIndexFreshness(repoRoot, existing);
  if (freshness.status === 'missing') {
    throw new CodeMapGeneratorError('missing_source_index', 'Source index is missing. Run `tenbo-dashboard index` to build it, then retry `code-map generate`.');
  }
  if (freshness.status === 'corrupt') {
    throw new CodeMapGeneratorError('corrupt_source_index', 'Source index cache is corrupt. Run `tenbo-dashboard index` to rebuild it, then retry `code-map generate`.');
  }
  if (freshness.status === 'incompatible') {
    throw new CodeMapGeneratorError('incompatible_source_index', 'Source index schema is out of date. Run `tenbo-dashboard index` to rebuild it, then retry `code-map generate`.');
  }
  if (freshness.status === 'stale') {
    const rebuilt = buildSourceIndex(repoRoot);
    writeSourceIndex(repoRoot, rebuilt);
    return rebuilt;
  }
  return existing as SourceIndex;
}

// ---------------------------------------------------------------------------
// Selection + top-level generate/check entry point.
// ---------------------------------------------------------------------------

export interface CodeMapSelection {
  scope?: string;
  layer?: string;
}

interface LayerTarget {
  scope: Scope;
  layer: Layer;
}

function selectLayers(state: TenboState, selection: CodeMapSelection): LayerTarget[] {
  const scopes = selection.scope ? state.scopes.filter((scope) => scope.id === selection.scope) : state.scopes;
  if (selection.scope && scopes.length === 0) {
    throw new CodeMapGeneratorError('not_found', `Unknown scope '${selection.scope}'.`);
  }
  const out: LayerTarget[] = [];
  for (const scope of scopes) {
    for (const layer of scope.layers) {
      if (selection.layer && layer.id !== selection.layer) continue;
      out.push({ scope, layer });
    }
  }
  if (selection.layer && out.length === 0) {
    throw new CodeMapGeneratorError(
      'not_found',
      `Unknown layer '${selection.layer}'${selection.scope ? ` in scope '${selection.scope}'` : ''}.`,
    );
  }
  return out.sort((a, b) => a.scope.id.localeCompare(b.scope.id) || a.layer.id.localeCompare(b.layer.id));
}

export interface CodeMapLayerResult {
  scope: string;
  layer: string;
  /** Repo-relative path to the layer's `code-map.md`. */
  path: string;
  /** Whether the file already had a marker pair before this run. */
  had_marker: boolean;
  /** Whether the generated region differs from what is currently on disk. */
  changed: boolean;
  content_hash: string;
  /** The generated structural markdown body (without marker lines), for display. */
  block: string;
}

export interface CodeMapGenerateResult {
  ok: true;
  mode: 'generate' | 'check';
  layers: CodeMapLayerResult[];
  /** `scope:layer` keys whose region is stale vs. what's on disk. */
  stale_layers: string[];
}

/**
 * Generates (or, with `check: true`, only diffs) the marked structural
 * region for each selected layer's `code-map.md`. Never writes in check
 * mode. Returns per-layer results plus a flat `stale_layers` list so the
 * CLI can exit non-zero when `--check` finds drift.
 */
export function generateCodeMaps(repoRoot: string, opts: CodeMapSelection & { check?: boolean } = {}): CodeMapGenerateResult {
  const index = loadIndexForGeneration(repoRoot);
  const state = readState(repoRoot);
  const targets = selectLayers(state, opts);

  const layers: CodeMapLayerResult[] = [];
  const staleLayers: string[] = [];

  for (const { scope, layer } of targets) {
    const { body, hash } = buildStructuralBlock(index, scope, layer);
    const existing = readLayerDocFile(repoRoot, scope.id, layer.id, 'code-map.md') ?? '';
    const result = upsertMarkedRegion(existing, body, layer.name);
    const relPath = `.tenbo/scopes/${scope.id}/layers/${layer.id}/code-map.md`;

    if (!opts.check && result.changed) {
      writeLayerDocFile(repoRoot, scope.id, layer.id, 'code-map.md', result.content);
    }
    if (result.changed) staleLayers.push(`${scope.id}:${layer.id}`);

    layers.push({
      scope: scope.id,
      layer: layer.id,
      path: relPath,
      had_marker: result.hadMarker,
      changed: result.changed,
      content_hash: hash,
      block: body,
    });
  }

  return {
    ok: true,
    mode: opts.check ? 'check' : 'generate',
    layers,
    stale_layers: staleLayers,
  };
}
